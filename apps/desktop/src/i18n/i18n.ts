export function sanitizeLanguage(value: unknown): AppLanguage {
  return value === "en-US" ? "en-US" : "zh-CN";
}

export function getNextLanguage(language: AppLanguage): AppLanguage {
  return language === "zh-CN" ? "en-US" : "zh-CN";
}

export function createTranslator(language: AppLanguage): Translate {
  return (source, values = {}) => {
    const template = language === "en-US" ? (englishMessages[source] ?? source) : source;
    return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/gu, (match, key: string) =>
      Object.hasOwn(values, key) ? String(values[key]) : match,
    );
  };
}

export function readLanguagePreference(database: LocalDatabase): AppLanguage {
  return database.readDocument(LANGUAGE_COLLECTION, {
    version: LANGUAGE_DOCUMENT_VERSION,
    fallback: "zh-CN",
    sanitize: (value) => sanitizeLanguage(value),
  });
}

export function writeLanguagePreference(database: LocalDatabase, language: AppLanguage): void {
  database.writeDocument(LANGUAGE_COLLECTION, LANGUAGE_DOCUMENT_VERSION, language);
}
